const fs = require('fs');
const path = require('path');
const MARKETING_DIR = path.join(__dirname, '..', 'posts', 'marketing');
if (!fs.existsSync(MARKETING_DIR)) fs.mkdirSync(MARKETING_DIR, { recursive: true });
const ARQ = path.join(MARKETING_DIR, 'relatorio-conteudo-por-concorrencia-conteudo.json');

let cache = null;
function carregar() {
  if (cache) return cache;
  try { if (fs.existsSync(ARQ)) cache = JSON.parse(fs.readFileSync(ARQ, 'utf8')); } catch (e) {}
  cache = { relatorios: [], proximoId: 1, criadoEm: new Date().toISOString(), atualizadoEm: new Date().toISOString() };
  return cache;
}
function salvar() {
  try { cache.atualizadoEm = new Date().toISOString(); fs.writeFileSync(ARQ, JSON.stringify(cache, null, 2), 'utf8'); } catch (e) {}
}

function gerarRelatorioConteudoPorConcorrenciaConteudo(concorrente, jogo, tipo, engajamento, alcance) {
  const c = carregar();
  const id = 'rccn_' + c.proximoId++;
  const r = { id, concorrente: concorrente || '', jogo: jogo || 'ambos', tipo: tipo || '', engajamento: Number(engajamento) || 0, alcance: Number(alcance) || 0, geradoEm: new Date().toISOString(), enviado: false };
  c.relatorios.push(r);
  salvar();
  return { ok: true, relatorio: r };
}

function listarRelatoriosConteudoPorConcorrenciaConteudo(jogo = null, concorrente = null) {
  const c = carregar();
  let l = c.relatorios;
  if (jogo) l = l.filter(x => x.jogo === jogo || x.jogo === 'ambos');
  if (concorrente) l = l.filter(x => x.concorrente === concorrente);
  return l.sort((a, b) => b.engajamento - a.engajamento);
}

function marcarConteudoPorConcorrenciaConteudoEnviado(id) {
  const c = carregar();
  const r = c.relatorios.find(x => x.id === id);
  if (!r) return { ok: false, erro: 'Relatório não encontrado' };
  r.enviado = true;
  salvar();
  return { ok: true, relatorio: r };
}

function estatisticasConteudoPorConcorrenciaConteudo() {
  const c = carregar();
  const total = c.relatorios.length;
  const totalEngajamento = c.relatorios.reduce((s, r) => s + r.engajamento, 0);
  return { total, totalEngajamento, enviados: c.relatorios.filter(x => x.enviado).length };
}

module.exports = { gerarRelatorioConteudoPorConcorrenciaConteudo, listarRelatoriosConteudoPorConcorrenciaConteudo, marcarConteudoPorConcorrenciaConteudoEnviado, estatisticasConteudoPorConcorrenciaConteudo, carregar, salvar, ARQ };