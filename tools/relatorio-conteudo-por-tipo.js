const fs = require('fs');
const path = require('path');
const MARKETING_DIR = path.join(__dirname, '..', 'posts', 'marketing');
if (!fs.existsSync(MARKETING_DIR)) fs.mkdirSync(MARKETING_DIR, { recursive: true });
const ARQ = path.join(MARKETING_DIR, 'relatorio-conteudo-por-tipo.json');

let cache = null;
function carregar() {
  if (cache) return cache;
  try { if (fs.existsSync(ARQ)) cache = JSON.parse(fs.readFileSync(ARQ, 'utf8')); } catch (e) {}
  cache = { relatorios: [], proximoId: 1, criadoEm: new Date().toISOString(), atualizadoEm: new Date().toISOString() };
  return cache;
}
function salvar() {
  try { cache.atualizadoEm = new Date().toISOString(); fs.writeFileSync(ARQ, JSON.stringify(cache, null, 2), 'utf8'); } catch (e) {}
}

function gerarRelatorioConteudoPorTipo(tipo, jogo, rede, periodo, quantidade, engajamentoTotal, visualizacoesTotal) {
  const c = carregar();
  const id = 'ctp_' + c.proximoId++;
  const r = { id, tipo: tipo || '', jogo: jogo || 'ambos', rede: rede || 'todos', periodo: periodo || '', quantidade: Number(quantidade) || 0, engajamentoTotal: Number(engajamentoTotal) || 0, visualizacoesTotal: Number(visualizacoesTotal) || 0, mediaEngajamento: Number(quantidade) > 0 ? (Number(engajamentoTotal) / Number(quantidade)).toFixed(2) : 0, geradoEm: new Date().toISOString(), enviado: false };
  c.relatorios.push(r);
  salvar();
  return { ok: true, relatorio: r };
}

function listarRelatoriosConteudoPorTipo(jogo = null, tipo = null) {
  const c = carregar();
  let l = c.relatorios;
  if (jogo) l = l.filter(x => x.jogo === jogo || x.jogo === 'ambos');
  if (tipo) l = l.filter(x => x.tipo === tipo);
  return l.sort((a, b) => b.engajamentoTotal - a.engajamentoTotal);
}

function marcarConteudoPorTipoEnviado(id) {
  const c = carregar();
  const r = c.relatorios.find(x => x.id === id);
  if (!r) return { ok: false, erro: 'Relatório não encontrado' };
  r.enviado = true;
  salvar();
  return { ok: true, relatorio: r };
}

function estatisticasConteudoPorTipo() {
  const c = carregar();
  const total = c.relatorios.length;
  const totalEngajamento = c.relatorios.reduce((s, r) => s + r.engajamentoTotal, 0);
  return { total, totalEngajamento, enviados: c.relatorios.filter(x => x.enviado).length };
}

module.exports = { gerarRelatorioConteudoPorTipo, listarRelatoriosConteudoPorTipo, marcarConteudoPorTipoEnviado, estatisticasConteudoPorTipo, carregar, salvar, ARQ };